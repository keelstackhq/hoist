//! `hoist changeset init`: write `.changeset/config.json` and `README.md` (as `changeset init`).

use super::{created, report};
use crate::config::NpmAccess;
use crate::error::HoistError;
use crate::release::read_release_model;
use crate::repo::git::origin_head;
use crate::report::Report;
use std::io::Write;
use std::path::Path;

const README: &str = "# Changesets

Hello and welcome! This folder has been automatically generated by `@changesets/cli`, a build tool that works
with multi-package repos, or single-package repos to help you version and publish your code. You can
find the full documentation for it [in our repository](https://github.com/changesets/changesets)

We have a quick list of common questions to get you started engaging with this project in
[our documentation](https://github.com/changesets/changesets/blob/main/docs/common-questions.md)
";

fn config_text(base_branch: &str, access: &str) -> String {
    format!(
        "{{\n  \"$schema\": \"https://unpkg.com/@changesets/config@3.1.4/schema.json\",\n  \
         \"changelog\": \"@changesets/cli/changelog\",\n  \"commit\": false,\n  \"fixed\": [],\n  \
         \"linked\": [],\n  \"access\": \"{access}\",\n  \"baseBranch\": {base},\n  \
         \"updateInternalDependencies\": \"patch\",\n  \"ignore\": []\n}}\n",
        base = serde_json::to_string(base_branch).expect("string"),
    )
}

fn write_new(dir: &Path, rel: &str, text: &str) -> Result<(), HoistError> {
    let io = |e: std::io::Error| HoistError::Io(format!("cannot write {rel}: {e}"));
    let mut f = std::fs::OpenOptions::new()
        .write(true)
        .create_new(true)
        .open(dir.join(rel))
        .map_err(io)?;
    f.write_all(text.as_bytes()).map_err(io)
}

pub fn init(dir: &Path) -> Result<Report, HoistError> {
    if dir.join(".changeset/config.json").exists() {
        return Err(HoistError::Usage(
            ".changeset/config.json exists; edit it, or delete it and run `hoist changeset init` again"
                .into(),
        ));
    }
    let base = origin_head(dir)?.unwrap_or_else(|| "main".into());
    // `access` follows `[publish] npm.access`; a repo without a readable release model (a fresh
    // repo) gets changesets' own default.
    let access = read_release_model(dir)
        .ok()
        .and_then(|m| {
            m.packages
                .iter()
                .find_map(|p| p.publish.npm.as_ref().map(|n| n.access))
        })
        .map_or("restricted", |a| match a {
            NpmAccess::Public => "public",
            NpmAccess::Restricted => "restricted",
        });
    std::fs::create_dir_all(dir.join(".changeset"))
        .map_err(|e| HoistError::Io(format!("cannot create .changeset/: {e}")))?;
    write_new(dir, ".changeset/config.json", &config_text(&base, access))?;
    let mut items = vec![created(
        "config",
        "config.json",
        ".changeset/config.json",
        format!("baseBranch {base}, access {access}"),
    )];
    if !dir.join(".changeset/README.md").exists() {
        write_new(dir, ".changeset/README.md", README)?;
        items.push(created(
            "config",
            "README.md",
            ".changeset/README.md",
            "how changesets work".into(),
        ));
    }
    Ok(report("changeset init", items))
}
